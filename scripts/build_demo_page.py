#!/usr/bin/env python3
"""Make the hosted demo page from a generated `saga duo` export.

The source must be a real per-person Wrapped produced from the synthetic demo
vault (see docs/DEMO.md). The output keeps every generated statistic and quote.
Two things change for hosting: the provider-player hook is removed, because the
website must not load third-party content even on click, and the scroll-reveal
script is removed so the page is a single static document with no scripts at all.

Usage:
  python3 scripts/build_demo_page.py --source <duo-jules.html> --out site/demo/index.html
"""
import argparse
import re
import sys
from pathlib import Path

BANNER = (
    '<div class="sample-band" role="note">'
    'Sample archive, generated by <code>saga demo</code>.'
    '</div>'
)
EXTRA_HEAD = (
    '<meta name="description" content="A sample per-person Wrapped page generated by Saga '
    'from its demo archive.">\n'
    '<meta name="color-scheme" content="dark">\n'
    '<meta name="robots" content="noindex">\n'
    '<link rel="icon" href="../assets/favicon.png" type="image/png">\n'
)
EXTRA_STYLE = """<style>
/* Website additions: the reveal animation is dropped for the hosted copy, so
   every section is visible without JavaScript, and a provenance band sits at
   the top of the page. */
.reveal { opacity: 1 !important; transform: none !important; }
.sample-band {
  position: sticky; top: 0; z-index: 5;
  padding: 10px 18px; font-size: 13.5px; line-height: 1.35; text-align: center;
  color: #dff1ec; background: #075E54; border-bottom: 1px solid rgba(37, 211, 102, 0.28);
}
.sample-band code { color: #DCF8C6; }
</style>
"""


def build(source: str) -> str:
    if '<title>' not in source:
        raise SystemExit('source does not look like a generated Wrapped page')
    # Provider players: the export builds them on click. The website must never load
    # third-party content, so the hook, the buttons that call it and the tracking-free
    # "Open in …" anchors all become inert. The service name stays as plain text, because
    # which service a link came from is part of the story.
    source, removed = re.subn(
        r'\n?<script>function play\(id, src, h\) \{.*?</script>', '\n', source, count=1, flags=re.S)
    if not removed:
        raise SystemExit('expected the play()/reveal script from DuoWrappedHTML; source changed?')
    source, buttons = re.subn(
        r'<button class="play" onclick="play\([^"]*\)">[^<]*</button>\s*', '', source)
    if not buttons:
        raise SystemExit('expected play buttons from DuoWrappedHTML; source changed?')
    source, anchors = re.subn(
        r'<a class="open" href="[^"]*" target="_blank" rel="noopener">([^<]*)</a>',
        r'<span class="open">\1</span>', source)
    if not anchors:
        raise SystemExit('expected provider links from DuoWrappedHTML; source changed?')
    # The reveal animation is driven by a class the page's own script would add; with no
    # script the class is meaningless, so drop the token rather than leaving content hidden.
    def drop_reveal(match):
        tokens = [t for t in match.group(1).split() if t != 'reveal']
        return 'class="%s"' % ' '.join(tokens) if tokens else ''
    source = re.sub(r'class="([^"]*)"', drop_reveal, source)
    source = source.replace('<html>', '<html lang="en">', 1)
    source = source.replace(
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">\n' + EXTRA_HEAD, 1)
    source = source.replace('</head>', EXTRA_STYLE + '</head>', 1)
    source = source.replace('<body>', '<body>\n' + BANNER, 1)
    # Keyboard users need somewhere to land inside the frame so arrows/page keys
    # scroll the sample instead of the outer page.
    source = source.replace('<main>', '<main tabindex="0" aria-label="Sample Wrapped page">', 1)
    for forbidden in ('<script', 'play(', 'spotify.com/embed', 'w.soundcloud.com/player', 'youtube.com/embed'):
        if forbidden in source:
            raise SystemExit(f'derivative still contains an executable or provider hook: {forbidden}')
    if re.search(r'src=|https?://', source):
        raise SystemExit('derivative still contains an external reference')
    if re.search(r'class="[^"]*\breveal\b', source):
        raise SystemExit('derivative still hides content behind the reveal animation')
    return source


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, help='generated duo Wrapped HTML')
    parser.add_argument('--out', required=True, help='destination, e.g. site/demo/index.html')
    args = parser.parse_args()
    output = build(Path(args.source).read_text(encoding='utf-8'))
    destination = Path(args.out)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output, encoding='utf-8')
    print(f'wrote {destination} ({len(output)} bytes); static HTML, no scripts, no external references')
    return 0


if __name__ == '__main__':
    sys.exit(main())
