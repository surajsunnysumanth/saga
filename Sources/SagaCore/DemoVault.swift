import Foundation

/// Public, offline fixture. No device, contacts, user preferences or existing vault is read.
///
/// Everything in it is generated: the people, the chats, the words, the dates, the attachments.
/// Only the *shape* of an archive is borrowed — three years, a handful of groups, one loud group,
/// a quiet stretch — never its content, and never partially-redacted text.
public enum DemoVault {
    public enum GenerationError: LocalizedError {
        case destinationExists
        case photosFolderMissing(String)
        case photosFolderEmpty(String)
        case photosUnreadable(String)
        public var errorDescription: String? {
            switch self {
            case .destinationExists:
                return "The demo destination already exists. Choose a new folder with saga demo --out <new-folder>; existing files are never replaced."
            case .photosFolderMissing(let p):
                return "\(p) is not a folder. Pass a folder of image files to --photos, or omit the flag to use the drawn scenes."
            case .photosFolderEmpty(let p):
                return "\(p) holds no image files. Pass a folder of jpg/png/webp/heic pictures to --photos, or omit the flag to use the drawn scenes."
            case .photosUnreadable(let name):
                return "Could not decode \(name) as an image. Remove it from the --photos folder or re-export it as JPEG or PNG."
            }
        }
    }

    public enum LaunchError: LocalizedError {
        case missingFolder, notDemo(String)
        public var errorDescription: String? {
            switch self {
            case .missingFolder: return "--demo needs a folder made by `saga demo --out <folder>`."
            case .notDemo(let p): return "\(p) is not a Saga demo folder (run `saga demo --out <new-folder>` first). Refusing to fall back to real data."
            }
        }
    }

    /// Parses `--demo <folder>`. nil when absent; throws when malformed or the folder is not a generated demo.
    public static func launchDirectory(arguments: [String]) throws -> URL? {
        guard let i = arguments.firstIndex(of: "--demo") else { return nil }
        guard i + 1 < arguments.count, !arguments[i + 1].hasPrefix("--") else { throw LaunchError.missingFolder }
        let dir = URL(fileURLWithPath: arguments[i + 1]).standardizedFileURL
        let meta = dir.appendingPathComponent("vault/vault.json")
        guard let data = try? Data(contentsOf: meta),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any], json["synthetic"] as? Bool == true,
              FileManager.default.fileExists(atPath: dir.appendingPathComponent("vault_index.db").path)
        else { throw LaunchError.notDemo(dir.path) }
        return dir
    }

    /// True when `indexURL` sits inside a folder generated by `saga demo` (sibling `vault/vault.json` says `"synthetic": true`).
    /// Used to keep the Mac account name out of artifacts made from demo data.
    public static func isSyntheticDemo(indexURL: URL) -> Bool {
        let meta = indexURL.deletingLastPathComponent().appendingPathComponent("vault/vault.json")
        guard let data = try? Data(contentsOf: meta),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
        else { return false }
        return json["synthetic"] as? Bool == true
    }

    /// Creates a new support-style folder: vault/, media/ and the disposable vault_index.db.
    /// The seed, dates and identities are fixed, so the same command produces the same archive.
    ///
    /// `photos` is optional. When given, every image attachment is one of those photographs
    /// (read in filename order, then cycled in Gallery order) instead of a drawn scene; the
    /// rest of the archive is identical.
    @discardableResult
    public static func generate(at destination: URL, photos: URL? = nil) throws -> ImportSummary {
        let fm = FileManager.default
        let output = destination.standardizedFileURL
        guard !fm.fileExists(atPath: output.path), (try? fm.destinationOfSymbolicLink(atPath: output.path)) == nil else {
            throw GenerationError.destinationExists
        }
        // Read before staging, so a bad folder fails without leaving a half-made destination.
        let photoData = try DemoPhotoSource.load(from: photos)
        let parent = output.deletingLastPathComponent()
        try fm.createDirectory(at: parent, withIntermediateDirectories: true)
        let stage = parent.appendingPathComponent(".saga-demo-\(UUID().uuidString)")
        try fm.createDirectory(at: stage, withIntermediateDirectories: false)
        defer { try? fm.removeItem(at: stage) }

        let vault = try Vault(url: stage.appendingPathComponent("vault"))
        let stamp = "2026-11-01T09:00:00Z"
        let metadata: [String: Any] = ["app": "saga", "format": 1, "id": "00000000-0000-4000-8000-000000000001",
                                       "created": stamp, "synthetic": true, "fixture": 2]
        try JSONSerialization.data(withJSONObject: metadata, options: [.prettyPrinted, .sortedKeys])
            .write(to: vault.url.appendingPathComponent("vault.json"))

        var rng = DemoRandom(seed: DemoFixture.seed)
        let plans = DemoFixture.plans()

        // 1. Write the conversations, then place the features that Wrapped and On This Day rely on.
        var conversations: [(plan: DemoChatPlan, messages: [DemoMessage])] = []
        var linksPlaced = 0, quotesPlaced = 0, gonePlaced = 0, reactionsPlaced = 0, stickersPlaced = 0
        for (index, plan) in plans.enumerated() {
            var messages = DemoFixture.generate(plan, rng: &rng)
            DemoFixture.sortChronologically(&messages)
            DemoFixture.addFeatures(&messages, plan: plan, chatIndex: index, rng: &rng)
            DemoFixture.addReactions(&messages, plan: plan, rng: &rng)
            DemoFixture.addStickers(&messages, plan: plan, rng: &rng)
            // End one DM on an incoming question so the reply sheet has demo evidence. This only
            // rewrites an existing message, so the fixture's counts and dates do not move.
            if plan.jid == "demo-priya@lid" { DemoFixture.plantUnansweredQuestion(&messages, plan: plan) }
            DemoFixture.assignIdentities(&messages, chatIndex: index, jid: plan.jid)
            linksPlaced += messages.reduce(0) { $0 + ($1.text?.contains("http") == true ? 1 : 0) }
            quotesPlaced += messages.filter { $0.quoteIndex != nil }.count
            gonePlaced += messages.filter(\.gone).count
            reactionsPlaced += messages.reduce(0) { $0 + $1.reacts.count }
            stickersPlaced += messages.filter { $0.type == 20 }.count
            conversations.append((plan, messages))
        }

        // 2. Number the photographs in reverse-date order — the order the Gallery shows them —
        //    so a screenful cycles through the folder instead of repeating one picture. Then
        //    write one attachment file per attachment row (a photograph or a drawn scene, a
        //    silent clip, a tone, a PDF).
        var photoIndexByMessage: [String: Int] = [:]
        if !photoData.isEmpty {
            var dated: [(uid: String, ts: Int64)] = []
            for (_, messages) in conversations {
                for m in messages where m.media?.kind == "image" {
                    dated.append((m.uid, m.ts))
                }
            }
            dated.sort { $0.ts != $1.ts ? $0.ts > $1.ts : $0.uid > $1.uid }
            for (rank, image) in dated.enumerated() {
                photoIndexByMessage[image.uid] = rank % photoData.count
            }
        }
        var writer = DemoMediaWriter(root: stage.appendingPathComponent("media"), rng: &rng, photos: photoData)
        for c in conversations.indices {
            for m in conversations[c].messages.indices where conversations[c].messages[m].media != nil {
                var media = conversations[c].messages[m].media!
                try writer.materialise(&media, ts: conversations[c].messages[m].ts, rng: &rng,
                                       photoIndex: photoIndexByMessage[conversations[c].messages[m].uid])
                conversations[c].messages[m].media = media
            }
        }

        // 3. Vault records: chats, the cast, messages, quotes, deletions.
        var records: [[String: Any]] = [["k": "seg", "fmt": 1, "created": stamp, "source": "synthetic-demo",
                                         "label": "Public demo — entirely fictional"]]
        for plan in plans {
            records.append(["k": "chat", "jid": plan.jid, "j": plan.jid, "g": plan.isGroup ? 1 : 0,
                            "n": plan.name, "sub": plan.name])
        }
        for person in DemoCorpus.cast {
            records.append(["k": "j", "j": "demo-\(person.user)@lid", "n": person.name])
        }
        for (plan, messages) in conversations {
            for m in messages {
                var r: [String: Any] = ["k": "m", "u": m.uid, "c": plan.jid, "fm": m.fromMe ? 1 : 0,
                                        "ts": m.ts, "ty": m.type, "kid": m.kid]
                if let text = m.text, !text.isEmpty { r["tx"] = text }
                if !m.fromMe, let sender = m.sender {
                    r["s"] = ["j": "demo-\(sender)@lid", "n": DemoCorpus.name[sender] ?? sender]
                }
                if let media = m.media {
                    var md: [String: Any] = ["mime": media.mime, "path": media.relPath, "size": media.size, "hash": media.hash]
                    if let caption = media.caption { md["cap"] = caption }
                    r["md"] = md
                }
                records.append(r)
                for react in m.reacts {
                    var rr: [String: Any] = ["k": "r", "u": m.uid, "e": react.emoji]
                    if let by = react.by { rr["j"] = "demo-\(by)@lid"; rr["n"] = DemoCorpus.name[by] ?? by } else { rr["me"] = 1 }
                    records.append(rr)
                }
                if let target = m.quoteIndex, target < messages.count {
                    records.append(["k": "q", "u": m.uid, "t": messages[target].uid])
                }
                if m.gone { records.append(["k": "gone", "u": m.uid, "at": stamp]) }
            }
        }

        var body = Data()
        body.reserveCapacity(records.count * 160)
        for record in records {
            body.append(try JSONSerialization.data(withJSONObject: record, options: [.sortedKeys, .withoutEscapingSlashes]))
            body.append(10)
        }
        try Gzip.compress(body).write(to: vault.segmentsDir.appendingPathComponent("seg-demo-v2.ndjson.gz"))

        // 4. Vault config the app reads: the merged identity, and where the placeholder media lives.
        let config = vault.url.appendingPathComponent("config")
        try fm.createDirectory(at: config, withIntermediateDirectories: true)
        let merge: [String: Any] = ["merges": [["keys": ["lid:demo-nikhil", "lid:demo-nikhil-old"], "name": "Nikhil Rao"]]]
        try JSONSerialization.data(withJSONObject: merge, options: [.prettyPrinted, .sortedKeys])
            .write(to: config.appendingPathComponent("merges.json"))
        let mediaSource = output.appendingPathComponent("media").path
        try JSONSerialization.data(withJSONObject: [mediaSource], options: [.sortedKeys])
            .write(to: config.appendingPathComponent("media-sources.json"))

        let summary = try VaultIndexer.build(vault: vault, out: stage.appendingPathComponent("vault_index.db").path)
        try """
        # Saga synthetic demo (fixture v2)
        Entirely fictional and generated offline; safe for public screenshots. No real contacts,
        phone numbers, messages, media or backups were used, and nothing here is copied from a
        real conversation. IDs prefixed demo- are not real accounts.

        \(summary.messages) messages across \(summary.chats) chat records
        (4 people in one-to-one chats — one of them on two merged numbers — and
        \(plans.filter(\.isGroup).count) groups), \(DemoFixture.firstDay) to \(DemoFixture.lastDay),
        with a quiet month and a quieter year.
        \(linksPlaced) music and video links (public catalogue pages that really exist), \(summary.media)
        generated attachments in media/ (never photographs), \(quotesPlaced) quoted replies, \(reactionsPlaced)
        emoji reactions, \(stickersPlaced) stickers, \(gonePlaced) messages later deleted on the phone.

        vault/              open-format archive (vault.json says "synthetic": true)
        media/              generated placeholder attachments, referenced by config/media-sources.json
        vault_index.db      disposable local index
        vault_index.db is rebuilt with: saga vault index --vault '<this-folder>/vault' --out '<new-index.db>'

        The media folder is recorded as an absolute path, so generate again after moving this folder.
        See docs/DEMO.md in the Saga repository for browsing and screenshot instructions.
        """.write(to: stage.appendingPathComponent("README.txt"), atomically: true, encoding: .utf8)


        // Publishing by rename prevents partial output and refuses a destination created meanwhile.
        try fm.moveItem(at: stage, to: output)
        return summary
    }
}
